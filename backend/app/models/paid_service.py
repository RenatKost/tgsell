"""Paid seller services + DB-backed app settings (migration 0051).

Payment = USDT TRC-20 to a per-order deposit address generated by the SAME
``generate_escrow_wallet()`` as deals. Detection is read-only (balanceOf); this
module never moves funds.
"""
from datetime import datetime

from sqlalchemy import DateTime, Float, ForeignKey, Integer, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column

from app.database import Base


class AppSetting(Base):
    """Key/value settings editable by admin without a deploy."""

    __tablename__ = "app_settings"

    key: Mapped[str] = mapped_column(String(64), primary_key=True)
    value: Mapped[str] = mapped_column(Text)
    updated_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)


class PaidServiceOrder(Base):
    __tablename__ = "paid_service_orders"

    id: Mapped[int] = mapped_column(primary_key=True)
    kind: Mapped[str] = mapped_column(String(20), index=True)  # top | post | verified
    channel_id: Mapped[int] = mapped_column(Integer, ForeignKey("channels.id", ondelete="CASCADE"), index=True)
    seller_id: Mapped[int] = mapped_column(Integer, ForeignKey("users.id"), index=True)
    price_usdt: Mapped[float] = mapped_column(Float)
    # awaiting_payment | active | expired | paid | in_review | published | verified | rejected | cancelled
    status: Mapped[str] = mapped_column(String(20), index=True, default="awaiting_payment")
    escrow_wallet_address: Mapped[str] = mapped_column(String(100))
    escrow_private_key_encrypted: Mapped[str] = mapped_column(Text)
    received_usdt: Mapped[float | None] = mapped_column(Float, nullable=True)
    payment_deadline_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    paid_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    active_until: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    admin_note: Mapped[str | None] = mapped_column(Text, nullable=True)
    handled_by_id: Mapped[int | None] = mapped_column(Integer, ForeignKey("users.id", ondelete="SET NULL"), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now())
    updated_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
